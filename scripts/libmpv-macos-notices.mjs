// Write src-tauri/licenses/libmpv-macos-THIRD-PARTY.txt (shipped in the macOS app as
// Contents/Resources/licenses/libmpv-THIRD-PARTY.txt) from the licence files in a
// vendored macOS libmpv bundle (scripts/fetch-libmpv.mjs, from the archive
// scripts/build-libmpv-macos.sh wrote). Run it after changing the build:
//
//   node scripts/libmpv-macos-notices.mjs [--arch arm64|x86_64]
//
// It fails if the bundle's licence files differ from the list below, so a new
// component cannot ship without its notice.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const arch = process.argv.includes("--arch")
  ? process.argv[process.argv.indexOf("--arch") + 1]
  : process.arch === "arm64" ? "arm64" : "x86_64";
const dir = join(root, "src-tauri", "libmpv-macos", arch, "licenses");

// [directory, display name, version, licence, home, files in order]
const COMPONENTS = [
  ["mpv", "mpv", "0.41.0", "LGPL-2.1-or-later", "https://github.com/mpv-player/mpv", ["Copyright", "LICENSE.LGPL"]],
  ["ffmpeg", "FFmpeg", "9.0.2", "LGPL-2.1-or-later", "https://ffmpeg.org/", ["LICENSE.md", "COPYING.LGPLv2.1"]],
  ["libplacebo", "libplacebo", "7.360.1", "LGPL-2.1-or-later", "https://code.videolan.org/videolan/libplacebo", ["LICENSE"]],
  ["fribidi", "FriBidi", "1.0.17", "LGPL-2.1-or-later", "https://github.com/fribidi/fribidi", ["COPYING", "AUTHORS"]],
  ["libass", "libass", "0.17.5", "ISC", "https://github.com/libass/libass", ["COPYING"]],
  ["freetype", "FreeType", "2.15.0", "FTL", "https://freetype.org/", ["LICENSE.TXT", "FTL.TXT"]],
  ["harfbuzz", "HarfBuzz", "14.6.0", "MIT", "https://github.com/harfbuzz/harfbuzz", ["COPYING"]],
  ["dav1d", "dav1d", "1.5.4", "BSD-2-Clause", "https://code.videolan.org/videolan/dav1d", ["COPYING"]],
  ["fast_float", "fast_float", "8.3.2", "MIT", "https://github.com/fastfloat/fast_float", ["LICENSE-MIT"]],
  ["glad", "glad", "2.0.8", "see below", "https://github.com/Dav1dde/glad", ["LICENSE", "Apache-2.0.txt"]],
  ["vulkan-headers", "Vulkan-Headers", "1.4.363.0", "MIT", "https://github.com/KhronosGroup/Vulkan-Headers", ["LICENSE.md", "MIT.txt"]],
];

const bar = "=".repeat(78);
const present = readdirSync(dir).sort();
const expected = COMPONENTS.map(([d]) => d).sort();
if (JSON.stringify(present) !== JSON.stringify(expected)) {
  throw new Error(`licence folders ${present.join(", ")} do not match ${expected.join(", ")}`);
}
const out = [
  `libmpv for macOS: third-party notices
${bar}

Zeiler for macOS ships libmpv and the libraries it loads in
Zeiler.app/Contents/Frameworks, each as its own dynamic library, for built-in playback.
They are built from unchanged upstream sources by scripts/build-libmpv-macos.sh; see
libmpv-NOTICE.txt for versions, provenance and the written source offer.

- mpv is built in its LGPL configuration (-Dgpl=false): GNU Lesser General Public
  License, version 2.1 or later (LGPL-2.1.txt).
- FFmpeg is built without --enable-gpl and without --enable-version3: GNU Lesser
  General Public License, version 2.1 or later (LGPL-2.1.txt).
- libplacebo and FriBidi: GNU Lesser General Public License, version 2.1 or later.
- libass (ISC), FreeType (FreeType License, chosen over its GPL-2.0 alternative),
  HarfBuzz (MIT) and dav1d (BSD-2-Clause) keep their own licences.
- Compiled into libplacebo: fast_float (MIT, chosen of MIT / Apache-2.0 / BSL-1.0);
  an OpenGL loader generated by glad, which glad marks
  "(WTFPL OR CC0-1.0) AND Apache-2.0" (the generated code is CC0-1.0, chosen of WTFPL /
  CC0-1.0; the Khronos registry it comes from is Apache-2.0, whose text follows glad's
  LICENSE below); and code built against the Khronos Vulkan headers (MIT, chosen of
  Apache-2.0 / MIT).

This file reproduces each project's licence files as its source release ships them
(the heading names the project and the file).
`,
  ...COMPONENTS.map(([, name, version, licence, home]) =>
    `  ${name.padEnd(15)}${version.padEnd(11)}${licence.padEnd(20)}${home}`),
  "",
];
for (const [d, name, , , , files] of COMPONENTS) {
  const have = readdirSync(join(dir, d)).sort();
  if (JSON.stringify(have) !== JSON.stringify([...files].sort())) {
    throw new Error(`${d}: licence files ${have.join(", ")}, expected ${files.join(", ")}`);
  }
  for (const f of files) {
    out.push(`${bar}\n${name}: ${f}\n${bar}\n\n${readFileSync(join(dir, d, f), "utf8").trimEnd()}\n`);
  }
}
writeFileSync(join(root, "src-tauri", "licenses", "libmpv-macos-THIRD-PARTY.txt"), out.join("\n"));
console.log("[libmpv-macos-notices] wrote src-tauri/licenses/libmpv-macos-THIRD-PARTY.txt");
